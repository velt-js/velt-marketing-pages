#!/usr/bin/env node
// unravel.mjs — turns app/home-static.jsx (the 2 MB Framer SSR blob) into a
// hand-editable starting point: extracts inline <style dangerouslySetInnerHTML>
// blocks into app/v2/unraveled.css, strips Framer runtime-hydration attributes
// that don't matter without the runtime, and writes the cleaned JSX to
// app/v2/unraveled.tsx as a React component ("Unraveled") that /v2/page.tsx
// can render directly.
//
// Idempotent. Safe to re-run after `app/home-static.jsx` is refreshed.
//
// Usage:
//   node scripts/unravel.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const SRC = path.join(ROOT, "app/home-static.jsx");
const OUT_CSS = path.join(ROOT, "app/v2/unraveled.css");
const OUT_TSX = path.join(ROOT, "app/v2/unraveled.tsx");

// Hydration-only attributes. Stripped because we're not loading the Framer
// runtime in /v2 — they're dead weight and bloat the DOM.
const STRIP_ATTRS = [
  "data-framer-appear-id",
  "data-framer-component-type",
  "data-framer-hydrate-v2",
  "data-framer-ssr-fallback",
  "data-framer-ssr-released-at",
  "data-framer-root",
  "data-framer-page-optimized-at",
  "data-framer-generated",
  "data-framer-generated-page",
  "data-framer-html-style",
  "data-framer-font-css",
  "data-framer-breakpoint-css",
  "data-framer-css-ssr-minified",
  "data-framer-components",
  "data-framer-legacy-stack-gap-enabled",
  "data-framer-stack-content-wrapper",
  "data-framer-stack-direction-reverse",
  "data-framer-stack-flexbox-gap",
  "data-framer-stack-gap-enabled",
];

// JavaScript string escape → real characters. The inline styles live inside
// `dangerouslySetInnerHTML={{__html: "..."}}`, so they're JS-escaped.
function unescapeJsString(s) {
  return s
    .replace(/\\\\/g, "\u0000") // placeholder for literal backslash
    .replace(/\\n/g, "\n")
    .replace(/\\t/g, "\t")
    .replace(/\\r/g, "\r")
    .replace(/\\"/g, '"')
    .replace(/\\'/g, "'")
    .replace(/\u0000/g, "\\");
}

function extractStyles(src) {
  // Match `<style ...attrs... dangerouslySetInnerHTML={{__html: "<css>" }} />`.
  // The CSS string uses JS-style escaping; we capture it with a tolerant
  // repetition that allows escaped chars.
  const re =
    /<style([^>]*?)dangerouslySetInnerHTML=\{\{__html:\s*"((?:[^"\\]|\\.)*)"\s*\}\}\s*\/>/g;
  const chunks = [];
  const cleaned = src.replace(re, (_match, attrs, content) => {
    const css = unescapeJsString(content);
    // Label each chunk by whatever data-framer-* attribute labels it.
    const label =
      attrs.match(/data-framer-[a-z0-9-]+/)?.[0] ?? "inline-style";
    chunks.push(`/* ${label} */\n${css}`);
    return "";
  });
  return { cleaned, chunks };
}

function stripAttrs(src) {
  for (const attr of STRIP_ATTRS) {
    // `attr="…"` — possibly multiline (the SSR block has 400 KB of CSS inside)
    src = src.replace(
      new RegExp(`\\s+${attr}="(?:[^"\\\\]|\\\\.)*"`, "g"),
      ""
    );
    // `attr='…'`
    src = src.replace(
      new RegExp(`\\s+${attr}='(?:[^'\\\\]|\\\\.)*'`, "g"),
      ""
    );
    // Bare boolean attr
    src = src.replace(new RegExp(`\\s+${attr}(?=[\\s/>])`, "g"), "");
  }
  return src;
}

function rewriteAsUnraveled(src) {
  // Replace the blob's default export so the file exports `Unraveled` instead
  // of `HomeStatic` (no collision with the original module).
  src = src.replace(
    /export default function HomeStatic\(\)/,
    "export default function Unraveled()"
  );
  // Inject a note at the top acknowledging the generator.
  src = src.replace(
    /^\/\/ @ts-nocheck/m,
    "// @ts-nocheck\n// AUTO-GENERATED by scripts/unravel.mjs from app/home-static.jsx —\n// re-run that script after refreshing home-static."
  );
  return src;
}

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`unravel.mjs: missing input ${SRC}`);
    process.exit(1);
  }
  const input = fs.readFileSync(SRC, "utf8");
  const before = Buffer.byteLength(input, "utf8");

  const { cleaned: noStyles, chunks } = extractStyles(input);
  const stripped = stripAttrs(noStyles);
  const finalTsx = rewriteAsUnraveled(stripped);
  const css = chunks.join("\n\n") + "\n";

  fs.mkdirSync(path.dirname(OUT_TSX), { recursive: true });
  fs.writeFileSync(OUT_TSX, finalTsx);
  fs.writeFileSync(OUT_CSS, css);

  const after = Buffer.byteLength(finalTsx, "utf8");
  const cssSize = Buffer.byteLength(css, "utf8");
  const shrink = (((before - after) / before) * 100).toFixed(1);
  console.log(`unravel.mjs:`);
  console.log(`  input      ${SRC}: ${before} bytes`);
  console.log(`  tsx output ${OUT_TSX}: ${after} bytes (-${shrink}%)`);
  console.log(`  css output ${OUT_CSS}: ${cssSize} bytes (${chunks.length} blocks)`);
}

main();
