// Escape path-to-regexp special characters so literal slugs (especially
// those containing parens) match correctly when used as a `source`
// pattern in next.config.ts redirects.
const PATH_TO_REGEXP_SPECIAL = /[()*+?:]/g;
function escapeForPathToRegexp(slug: string): string {
  return slug.replace(PATH_TO_REGEXP_SPECIAL, "\\$&");
}

export function buildBlogRedirectEntries() {
  return blogRedirects.map(({ from, to }) => ({
    source: `/blog/${escapeForPathToRegexp(from)}`,
    destination: `/blog/${to}`,
    permanent: true,
  }));
}
